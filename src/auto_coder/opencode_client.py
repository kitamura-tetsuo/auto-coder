def _read_only_special(name, args):
    if name == "branch":
        mutating = {"-d", "-D", "-m", "-M", "-c", "-C", "--delete", "--move", "--copy",
                     "--edit-description", "--set-upstream-to", "--unset-upstream"}
        if any(a in mutating for a in args):
            return False
        if any(a in {"--list", "-l", "--contains", "--no-contains", "--merged", "--no-merged"} for a in args):
            return True
        return not any(not a.startswith("-") for a in args)
    if name == "symbolic-ref":
        return len([a for a in args if not a.startswith("-")]) <= 1
    if name == "tag":
        return not any(not a.startswith("-") for a in args)
    if name == "config":
        mutating = {"--add", "--replace-all", "--unset", "--unset-all", "--rename-section",
                     "--remove-section", "--edit", "-e"}
        if any(a in mutating for a in args):
            return False
        if any(a in {"--get", "--get-all", "--get-regexp", "--get-urlmatch", "-l", "--list"} for a in args):
            return True
        return len([a for a in args if not a.startswith("-")]) <= 1
    if name == "remote":
        return not args or args[0] in {"-v", "show", "get-url"}
    if name == "worktree":
        return not args or args[0] == "list"
    return False


_GLOBAL_OPTIONS_WITH_SEPARATE_VALUE = {
    "-c", "-C", "--git-dir", "--work-tree", "--namespace", "--super-prefix",
    "--exec-path", "--config-env", "--attr-source",
}


def _split_global_options(argv):
    """Skip global `git` options (and their values) to find the real subcommand."""
    index = 0
    while index < len(argv):
        token = argv[index]
        if not token.startswith("-"):
            return token, argv[index + 1:]
        if token in _GLOBAL_OPTIONS_WITH_SEPARATE_VALUE:
            index += 2
            continue
        index += 1
    return None, []


def _explicit_targets(argv, env):
    """Resolve an explicit `--git-dir`/`--work-tree`/`-C` target without invoking git.

    Returns (explicit_git_dir_or_None, explicit_work_tree_or_None, effective_cwd)
    so a caller can decide whether an invocation could possibly touch the
    protected repository's Git metadata *or* its working tree, even before any
    ambient (cwd-discovered) repository is known.
    """
    cwd = os.getcwd()
    git_dir = env.get("GIT_DIR")
    work_tree = env.get("GIT_WORK_TREE")
    index = 0
    while index < len(argv):
        token = argv[index]
        if token == "-C":
            if index + 1 < len(argv):
                cwd = os.path.normpath(os.path.join(cwd, argv[index + 1]))
            index += 2
            continue
        if token.startswith("-C") and len(token) > 2:
            cwd = os.path.normpath(os.path.join(cwd, token[2:]))
            index += 1
            continue
        if token == "--git-dir":
            if index + 1 < len(argv):
                git_dir = argv[index + 1]
            index += 2
            continue
        if token.startswith("--git-dir="):
            git_dir = token[len("--git-dir="):]
            index += 1
            continue
        if token == "--work-tree":
            if index + 1 < len(argv):
                work_tree = argv[index + 1]
            index += 2
            continue
        if token.startswith("--work-tree="):
            work_tree = token[len("--work-tree="):]
            index += 1
            continue
        if not token.startswith("-"):
            break
        if token in _GLOBAL_OPTIONS_WITH_SEPARATE_VALUE:
            index += 2
            continue
        index += 1

    def _abs(path):
        if path is None:
            return None
        return os.path.normpath(path if os.path.isabs(path) else os.path.join(cwd, path))

    return _abs(git_dir), _abs(work_tree), cwd


def _resolves_to_protected_repo(argv, env):
    """True unless this invocation demonstrably cannot touch the protected repo."""
    explicit_git_dir, explicit_work_tree, cwd = _explicit_targets(argv, env)
    if explicit_work_tree is not None and explicit_work_tree in PROTECTED_GIT_DIRS:
        return True
    if explicit_git_dir is not None:
        return explicit_git_dir in PROTECTED_GIT_DIRS
    # No explicit --git-dir/GIT_DIR: resolution falls back to ambient discovery
    # from `cwd`. Ask the real, unwrapped git (a read-only query) what it
    # would resolve to; fail closed (treat as protected) if that cannot be
    # determined.
    try:
        probe = subprocess.run(
            [REAL_GIT, "rev-parse", "--path-format=absolute", "--git-dir"],
            cwd=cwd, capture_output=True, text=True, env=env, timeout=30,
        )
    except (OSError, subprocess.TimeoutExpired):
        return True
    if probe.returncode != 0:
        return True
    return probe.stdout.strip() in PROTECTED_GIT_DIRS


def main(argv):
    env = os.environ.copy()
    if not _resolves_to_protected_repo(argv, env):
        os.execv(REAL_GIT, [REAL_GIT] + argv)
    name, rest = _split_global_options(argv)
    if name in _READ_ONLY_COMMANDS or (name is not None and _read_only_special(name, rest)):
        os.execv(REAL_GIT, [REAL_GIT] + argv)
    sys.stderr.write(
        "auto-coder: 'git " + " ".join(argv) + "' is reserved to Auto-Coder and was denied "
        "before execution; Auto-Coder owns Git lifecycle mutations (Issue #2124 REQ-007).\\n"
    )
    sys.exit(1)


if __name__ == "__main__":
    main(sys.argv[1:])
